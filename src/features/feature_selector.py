def extract_metadata(
    dataframe: pd.DataFrame,
    entity_type: str,
) -> pd.DataFrame:
    """
    Extract temporal and entity-identification metadata from the
    original fused feature dataframe.

    Parameters
    ----------
    dataframe:
        Original fused dataframe BEFORE FeatureSelector.transform().

    entity_type:
        Either "bus" or "line".

    Returns
    -------
    DataFrame
        Metadata aligned row-by-row with the final feature matrix.
    """

    if entity_type not in {
        "bus",
        "line",
    }:

        raise ValueError(
            "entity_type must be either "
            "'bus' or 'line'."
        )

                                                                    
                     
                                                                    

    required = [
        "timestamp",
    ]

                                                                    
                              
                                                                    

    if entity_type == "bus":

        required.append(
            "bus_id"
        )

    else:

        required.append(
            "line_id"
        )

                                                                    
                                                          
        optional = [
            "from_bus",
            "to_bus",
            "in_service",
            "edge_in_operational_graph",
        ]

        for column in optional:

            if column in dataframe.columns:

                required.append(
                    column
                )

                                                                    
               
                                                                    

    missing = (
        set(required)
        - set(dataframe.columns)
    )

    if missing:

        raise ValueError(
            f"Cannot extract {entity_type} metadata. "
            f"Missing columns: {sorted(missing)}"
        )

                                                                    
                                  
                                                                    

    metadata = dataframe[
        required
    ].copy()

                                                                    
                          
                                                                    

    metadata[
        "timestamp"
    ] = pd.to_datetime(
        metadata[
            "timestamp"
        ],
        errors="coerce",
    )

    if metadata[
        "timestamp"
    ].isna().any():

        raise ValueError(
            f"{entity_type} metadata contains invalid "
            "timestamps."
        )

                                                                    
                                  
                                                                    

    entity_column = (
        "bus_id"
        if entity_type == "bus"
        else "line_id"
    )

    metadata[
        entity_column
    ] = pd.to_numeric(
        metadata[
            entity_column
        ],
        errors="coerce",
    )

    if metadata[
        entity_column
    ].isna().any():

        raise ValueError(
            f"{entity_type} metadata contains invalid "
            f"{entity_column} values."
        )

    metadata[
        entity_column
    ] = metadata[
        entity_column
    ].astype(int)

    return metadata.reset_index(
        drop=True
    )


                                                                        
      
                                                                        


