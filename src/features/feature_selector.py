"""
Feature selection and fusion for the power-grid anomaly detection
pipeline.

This module combines the feature families generated by:

    statistical.py
    electrical.py
    frequency.py
    graph.py

and produces a clean ML-ready feature matrix.

Pipeline
--------
Engineered features
        |
        v
Metadata separation
        |
        v
Missing-value filtering
        |
        v
Constant / low-variance filtering
        |
        v
Correlation pruning
        |
        v
Final feature matrix
        |
        +--> Standardized ML matrix
        |
        +--> Optional PCA representation

Important
---------
This is an UNSUPERVISED anomaly-detection pipeline.

We therefore do not use anomaly labels for feature selection.

The selector can be fitted on training/normal data and subsequently
applied to validation/test data without refitting.
"""

